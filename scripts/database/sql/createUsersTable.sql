--- Purpose: Defines the frontend users table and the functions the
--- backend uses to add/remove users and verify/update passwords.
--- The backend connects as a postgres role (e.g., ueatdb_read_write_user);
--- rows in this table are application users, not postgres roles.
--- Copyright: Ben Baker (UUSS) distributed under the MIT license.

--- Create the users table.
DROP TABLE IF EXISTS auth.users CASCADE;
CREATE TABLE auth.users(
    --- Stable numeric identifier; other tables should FK to this.
    user_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    --- The user name - e.g., jsmith or jsmith@utah.edu (stored
    --- lowercase).  Names end up in tokens, logs, and the frontend, so
    --- they are kept to a small character set.  Enforced here rather
    --- than only in the backend so a superuser seeding the first
    --- administrator cannot create a name the backend then refuses.
    --- The backend's user administration checks the same pattern.
    name TEXT UNIQUE NOT NULL
        CHECK (name ~ '^[a-z0-9._@-]{1,64}$'),
    --- The hashed password.  This is generated by something like
    --- libsodium's crypto_pwhash_str.  Plaintext never enters the db.
    password_hash TEXT NOT NULL CHECK (length(password_hash) > 0),
    --- May this user manage other users?  Global, not per-schema: user
    --- management does not range over regions.  Orthogonal to the
    --- schema permissions -- an admin reads and writes region data only
    --- if granted that like anyone else.  See createAdministration.sql.
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    --- Non-NULL means the account holds a password someone else issued
    --- (a new hire's, or a reset) and names the instant that password
    --- dies.  Cleared by auth.update_user_password -- changing the
    --- password IS the activation, with no second step to forget.
    provisional_until TIMESTAMPTZ DEFAULT NULL,
    --- When the account first held a password its owner chose (or was
    --- created directly with one).  NULL = never.  This is what keeps
    --- the sweep away from established users: a reset makes someone
    --- provisional again, and a user who forgot their password and
    --- missed the reset window must not be deleted for it.
    activated TIMESTAMPTZ DEFAULT NOW(),
    --- When the user was created.
    created TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    --- The last time the password was updated.
    password_updated TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    --- Last login, by password or by key.
    last_login TIMESTAMPTZ DEFAULT NULL
);

--- Adds a user.  Returns TRUE on success; FALSE if the name or
--- password hash is empty, the name is outside the table's pattern,
--- or the user already exists.
---
--- Ungated: it takes no actor and checks nothing.  It is granted to no
--- role, so only a superuser can call it directly -- that is how the
--- first administrator gets created, since every admin_ function
--- demands an existing administrator:
---
---     psql -d ueatdb -c "SELECT auth.add_user('jsmith', '\$argon2id\$...', TRUE);"
---
--- The backend calls auth.admin_add_user.
CREATE OR REPLACE FUNCTION auth.add_user(p_name TEXT, p_password_hash TEXT,
                                         p_is_admin BOOLEAN DEFAULT FALSE)
RETURNS BOOLEAN AS $$
BEGIN
    IF p_name IS NULL OR length(trim(p_name)) = 0 THEN
        RETURN FALSE;
    END IF;
    IF p_password_hash IS NULL OR length(p_password_hash) = 0 THEN
        RETURN FALSE;
    END IF;
    INSERT INTO auth.users (name, password_hash, is_admin)
        VALUES (lower(trim(p_name)), p_password_hash,
                COALESCE(p_is_admin, FALSE));
    RETURN TRUE;
EXCEPTION WHEN unique_violation OR check_violation THEN
    RETURN FALSE;
END;
$$ LANGUAGE plpgsql;

--- Creates a user holding an issued password, valid for p_valid_for.
--- Returns TRUE on success; FALSE on empty input, a name outside the
--- table's pattern, a non-positive interval, or an existing user.  Ungated and granted to no role; the
--- backend calls auth.admin_add_provisional_user.
---
--- The issued password is a live credential for as long as it lives,
--- so the caller should generate a distinct random one per user.  The
--- interval is an argument because the .sql files carry no site policy.
CREATE OR REPLACE FUNCTION auth.add_provisional_user(
    p_name TEXT, p_password_hash TEXT, p_valid_for INTERVAL)
RETURNS BOOLEAN AS $$
BEGIN
    IF p_name IS NULL OR length(trim(p_name)) = 0 THEN
        RETURN FALSE;
    END IF;
    IF p_password_hash IS NULL OR length(p_password_hash) = 0 THEN
        RETURN FALSE;
    END IF;
    IF p_valid_for IS NULL OR p_valid_for <= INTERVAL '0' THEN
        RETURN FALSE;
    END IF;
    INSERT INTO auth.users (name, password_hash, provisional_until,
                            activated)
        VALUES (lower(trim(p_name)), p_password_hash,
                NOW() + p_valid_for, NULL);
    RETURN TRUE;
EXCEPTION WHEN unique_violation OR check_violation THEN
    RETURN FALSE;
END;
$$ LANGUAGE plpgsql;

--- Fetches the stored hash for verification with something like
--- libsodium's crypto_pwhash_str_verify.  Returns NULL if no such user.
---
--- An issued password past its deadline is treated as already gone,
--- whether or not the sweep has run.  Otherwise the sweep schedule
--- silently becomes the real deadline.
CREATE OR REPLACE FUNCTION auth.get_password_hash(p_name TEXT)
RETURNS TEXT AS $$
    SELECT password_hash
      FROM auth.users
     WHERE name = lower(trim(p_name))
       AND (provisional_until IS NULL OR provisional_until > NOW());
$$ LANGUAGE sql;

--- TRUE if this account still holds an issued password.  The backend
--- calls this after verifying a password and, when TRUE, permits
--- nothing but the password change: the person on the other end has
--- proved only that they received the issued password.  NULL if there
--- is no such user.
CREATE OR REPLACE FUNCTION auth.user_must_change_password(p_name TEXT)
RETURNS BOOLEAN AS $$
    SELECT provisional_until IS NOT NULL
      FROM auth.users
     WHERE name = lower(trim(p_name));
$$ LANGUAGE sql;

--- The name as stored, given any spelling the lookups accept - e.g.,
--- ' JSmith ' gives 'jsmith'.  NULL if there is no such user.  Every
--- function here matches lower(trim(name)), so a login typed in capitals
--- succeeds; the backend puts THIS in the token, or the same person is
--- a different user to everything downstream of it.
CREATE OR REPLACE FUNCTION auth.get_user_name(p_name TEXT)
RETURNS TEXT AS $$
    SELECT name
      FROM auth.users
     WHERE name = lower(trim(p_name));
$$ LANGUAGE sql;

--- Deletes every never-activated account whose issued password has
--- expired, and returns how many went.  Keys and permissions cascade.
---
--- An established user who was reset and missed the window is NOT a
--- candidate (activated is set): their password simply stops working
--- until an administrator resets them again.  Forgetting a password
--- should not cost anyone their account.
---
--- Call it on a timer; the schedule is not load-bearing, because an
--- expired issued password cannot log in either way:
---     psql -d ueatdb -c 'SELECT auth.delete_expired_provisional_users();'
CREATE OR REPLACE FUNCTION auth.delete_expired_provisional_users()
RETURNS INTEGER AS $$
DECLARE n_deleted INTEGER;
BEGIN
    DELETE FROM auth.users
     WHERE provisional_until IS NOT NULL
       AND provisional_until <= NOW()
       AND activated IS NULL;
    GET DIAGNOSTICS n_deleted = ROW_COUNT;
    RETURN n_deleted;
END;
$$ LANGUAGE plpgsql;

--- Records a successful login.  Returns TRUE if the user was found.
--- The backend should call this after crypto_pwhash_str_verify succeeds.
CREATE OR REPLACE FUNCTION auth.record_login(p_name TEXT)
RETURNS BOOLEAN AS $$
DECLARE n_updated INTEGER;
BEGIN
    UPDATE auth.users
       SET last_login = NOW()
     WHERE name = lower(trim(p_name));
    GET DIAGNOSTICS n_updated = ROW_COUNT;
    RETURN n_updated > 0;
END;
$$ LANGUAGE plpgsql;

--- Removes a user.  Returns TRUE if a row was deleted.  Any rows in
--- auth.user_schema_permissions cascade away with the user.  Ungated
--- and granted to no role; the backend calls auth.admin_remove_user.
CREATE OR REPLACE FUNCTION auth.remove_user(p_name TEXT)
RETURNS BOOLEAN AS $$
DECLARE n_deleted INTEGER;
BEGIN
    DELETE FROM auth.users
     WHERE name = lower(trim(p_name));
    GET DIAGNOSTICS n_deleted = ROW_COUNT;
    RETURN n_deleted > 0;
END;
$$ LANGUAGE plpgsql;

--- Updates a user's own password.  Returns TRUE if the user was found
--- and the (non-empty) hash was set.
---
--- This is also the activation: it clears provisional_until, and stamps
--- activated the first time.  An issued password past its deadline is
--- refused rather than activated -- the sweep has just not caught it.
CREATE OR REPLACE FUNCTION auth.update_user_password(
    p_name TEXT, p_password_hash TEXT)
RETURNS BOOLEAN AS $$
DECLARE n_updated INTEGER;
BEGIN
    IF p_password_hash IS NULL OR length(p_password_hash) = 0 THEN
        RETURN FALSE;
    END IF;
    UPDATE auth.users
       SET password_hash = p_password_hash,
           password_updated = NOW(),
           provisional_until = NULL,
           activated = COALESCE(activated, NOW())
     WHERE name = lower(trim(p_name))
       AND (provisional_until IS NULL OR provisional_until > NOW());
    GET DIAGNOSTICS n_updated = ROW_COUNT;
    RETURN n_updated > 0;
END;
$$ LANGUAGE plpgsql;

--------------------------------------------------------------------------
---                          User public keys                           ---
--------------------------------------------------------------------------
--- PUBLIC keys only -- the private half never leaves the user's client.
--- Users register keys for programmatic/API access (a la SSH
--- authorized_keys); the backend verifies signatures with something
--- like libsodium's crypto_sign_verify_detached.
--- Keys are revoked, never deleted: the row is the audit trail of what
--- could authenticate when.  (Deleting the user still cascades.)

--- TRUE if p_public_key is a key the backend could verify with: for
--- ed25519, standard padded base64 (libsodium's
--- sodium_base64_VARIANT_ORIGINAL) of exactly 32 bytes.  The encoding
--- must also be canonical -- decode skips whitespace, so without that
--- check the same key with a newline in it would slip past UNIQUE and
--- identify a second user.  A row that fails this could never
--- authenticate and could not be fingerprinted for a listing, so the
--- table refuses it.  An algorithm the backend does not support is
--- FALSE; adding one means adding it here and in the backend.
CREATE OR REPLACE FUNCTION auth.is_valid_public_key(
    p_public_key TEXT, p_algorithm TEXT)
RETURNS BOOLEAN AS $$
BEGIN
    IF p_algorithm = 'ed25519' THEN
        RETURN length(decode(p_public_key, 'base64')) = 32
           AND encode(decode(p_public_key, 'base64'), 'base64') = p_public_key;
    END IF;
    RETURN FALSE;
EXCEPTION WHEN OTHERS THEN
    --- decode raises on anything that is not base64.
    RETURN FALSE;
END;
$$ LANGUAGE plpgsql IMMUTABLE;

--- The key's fingerprint, for telling keys apart in a listing:
--- 'SHA256:' then standard base64, padding stripped, of the SHA-256 of
--- the RAW 32 key bytes.  ssh-keygen -l hashes an SSH wire-format blob
--- instead, so the two are not comparable.  Computed here and nowhere
--- else so every listing agrees.
CREATE OR REPLACE FUNCTION auth.key_fingerprint(p_public_key TEXT)
RETURNS TEXT AS $$
    SELECT 'SHA256:'
        || rtrim(encode(sha256(decode(p_public_key, 'base64')), 'base64'), '=');
$$ LANGUAGE sql IMMUTABLE STRICT;

DROP TABLE IF EXISTS auth.user_keys CASCADE;
CREATE TABLE auth.user_keys(
    key_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES auth.users(user_id) ON DELETE CASCADE,
    --- User-facing label, e.g., 'laptop', 'ci-runner'.  Unique per
    --- user so 'revoke my laptop key' is unambiguous.  It reaches logs
    --- and screens, so it takes the user-name characters, lowercase.
    key_name TEXT NOT NULL CHECK (key_name ~ '^[a-z0-9._@-]{1,64}$'),
    --- The public key, e.g., base64 of libsodium crypto_sign_PUBLICKEYBYTES.
    --- Globally unique: one key must not identify two users.
    public_key TEXT NOT NULL CHECK (length(public_key) > 0)
        CONSTRAINT user_keys_public_key_key UNIQUE,
    --- Recorded so a future algorithm migration is data, not archaeology.
    algorithm TEXT NOT NULL DEFAULT 'ed25519'
        CHECK (algorithm = lower(algorithm)),
    created TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    --- NULL = no expiry.  A key that expired before it was registered
    --- is a mistake, not a key.
    expires TIMESTAMPTZ DEFAULT NULL
        CHECK (expires IS NULL OR expires > created),
    --- NULL = not revoked.  Set once; never unset.  Expiry does NOT set
    --- it: revoked records that someone acted (the user, an
    --- administrator, a compromise reset), expires that time ran out,
    --- and an audit wants to tell the two apart.  auth.key_states says
    --- which, if either, has happened.
    revoked TIMESTAMPTZ DEFAULT NULL,
    last_used TIMESTAMPTZ DEFAULT NULL,
    --- add_user_key tells the two UNIQUE failures apart by these names.
    CONSTRAINT user_keys_user_id_key_name_key UNIQUE (user_id, key_name),
    CHECK (auth.is_valid_public_key(public_key, algorithm))
);
CREATE INDEX user_keys_user_id_idx ON auth.user_keys(user_id);

--- Registers a public key for a user.  Returns TRUE on success and
--- FALSE only if the user doesn't exist.  Every other refusal RAISES,
--- with an SQLSTATE the backend can map to an answer for the user:
---
---   invalid_parameter_value (22023)  the key name breaks the naming
---       rule, the key is not one auth.is_valid_public_key accepts, or
---       p_expires is not in the future.  The message begins 'invalid
---       key name', 'invalid public key' or 'invalid expiration'.
---   duplicate_object (42710)  this user already has a key by this
---       name -- revoked ones included, since the row stays for audit.
---   unique_violation (23505)  the public key is registered already,
---       to anyone.  Only someone who proved they hold the private key
---       should be told this; see the backend's addKey.
---   insufficient_privilege (42501)  the user holds an issued
---       password.  A key outlives every password, so registering one
---       is the step that would turn an e-mailed password -- or a
---       stolen one that an administrator has since reset -- into
---       permanent access.
---   configuration_limit_exceeded (53400)  the user already has
---       p_max_active_keys active keys.  Revoked and expired keys do not
---       count, so revoking one makes room.
---
--- p_max_active_keys is the deployment's cap, passed in by the backend
--- from its configuration; NULL means no cap, and 0 means no keys at
--- all.  It is a parameter rather than a table so the backend's config
--- file stays the one place the policy is set.
---
--- The key name is trimmed and lowercased, like a user name.
DROP FUNCTION IF EXISTS
    auth.add_user_key(TEXT, TEXT, TEXT, TEXT, TIMESTAMPTZ);
CREATE OR REPLACE FUNCTION auth.add_user_key(
    p_name TEXT, p_key_name TEXT, p_public_key TEXT,
    p_algorithm TEXT DEFAULT 'ed25519', p_expires TIMESTAMPTZ DEFAULT NULL,
    p_max_active_keys INTEGER DEFAULT NULL)
RETURNS BOOLEAN AS $$
DECLARE v_user_id BIGINT;
        v_provisional TIMESTAMPTZ;
        v_key_name TEXT := lower(trim(p_key_name));
        v_public_key TEXT := trim(p_public_key);
        v_algorithm TEXT := lower(trim(p_algorithm));
        v_constraint TEXT;
BEGIN
    --- A misconfigured backend, not a user mistake.
    IF p_max_active_keys < 0 THEN
        RAISE EXCEPTION 'invalid key limit: % is negative', p_max_active_keys
              USING ERRCODE = 'invalid_parameter_value';
    END IF;
    IF v_key_name IS NULL OR v_key_name !~ '^[a-z0-9._@-]{1,64}$' THEN
        RAISE EXCEPTION 'invalid key name'
              USING ERRCODE = 'invalid_parameter_value',
                    HINT = 'Use 1 to 64 of a-z, 0-9, ., _, @ and -.';
    END IF;
    IF NOT COALESCE(auth.is_valid_public_key(v_public_key, v_algorithm),
                    FALSE) THEN
        RAISE EXCEPTION 'invalid public key'
              USING ERRCODE = 'invalid_parameter_value';
    END IF;
    IF p_expires IS NOT NULL AND p_expires <= NOW() THEN
        RAISE EXCEPTION 'invalid expiration: not in the future'
              USING ERRCODE = 'invalid_parameter_value';
    END IF;
    --- FOR UPDATE serializes one user's adds, so two at once cannot both
    --- count n - 1 active keys and both insert.
    SELECT user_id, provisional_until INTO v_user_id, v_provisional
      FROM auth.users WHERE name = lower(trim(p_name))
       FOR UPDATE;
    IF v_user_id IS NULL THEN
        RETURN FALSE;
    END IF;
    IF v_provisional IS NOT NULL THEN
        RAISE EXCEPTION 'password change required before adding a key'
              USING ERRCODE = 'insufficient_privilege';
    END IF;
    --- Checked first because, when both clash, the name is the answer to
    --- give: it is the user's own and says nothing about anyone else's
    --- keys.  The INSERT would report the key, as Postgres checks that
    --- index first.  The handler below still catches a concurrent add.
    IF EXISTS (SELECT 1 FROM auth.user_keys
                WHERE user_id = v_user_id AND key_name = v_key_name) THEN
        RAISE EXCEPTION 'key name already in use'
              USING ERRCODE = 'duplicate_object';
    END IF;
    IF p_max_active_keys IS NOT NULL AND
       (SELECT count(*) FROM auth.user_keys
         WHERE user_id = v_user_id
           AND revoked IS NULL
           AND (expires IS NULL OR expires > NOW())) >= p_max_active_keys THEN
        RAISE EXCEPTION 'too many active keys: the limit is %',
                        p_max_active_keys
              USING ERRCODE = 'configuration_limit_exceeded',
                    HINT = 'Revoke a key you no longer use.';
    END IF;
    BEGIN
        INSERT INTO auth.user_keys
            (user_id, key_name, public_key, algorithm, expires)
            VALUES (v_user_id, v_key_name, v_public_key, v_algorithm,
                    p_expires);
    EXCEPTION WHEN unique_violation THEN
        GET STACKED DIAGNOSTICS v_constraint = CONSTRAINT_NAME;
        IF v_constraint = 'user_keys_user_id_key_name_key' THEN
            RAISE EXCEPTION 'key name already in use'
                  USING ERRCODE = 'duplicate_object';
        END IF;
        RAISE EXCEPTION 'public key already registered'
              USING ERRCODE = 'unique_violation';
    END;
    RETURN TRUE;
END;
$$ LANGUAGE plpgsql;

--- Revokes a key by (user, key name).  Returns TRUE if an active key
--- was revoked.  The row remains for audit.
CREATE OR REPLACE FUNCTION auth.revoke_user_key(p_name TEXT, p_key_name TEXT)
RETURNS BOOLEAN AS $$
DECLARE n_updated INTEGER;
BEGIN
    UPDATE auth.user_keys k
       SET revoked = NOW()
      FROM auth.users u
     WHERE k.user_id = u.user_id
       AND u.name = lower(trim(p_name))
       AND k.key_name = lower(trim(p_key_name))
       AND k.revoked IS NULL;
    GET DIAGNOSTICS n_updated = ROW_COUNT;
    RETURN n_updated > 0;
END;
$$ LANGUAGE plpgsql;

--- The authentication workhorse: given a presented public key, return
--- the owning user's name -- but only if the key is active (not
--- revoked, not expired).  Returns NULL otherwise; the backend then
--- verifies the request signature against this key and, on success,
--- calls auth.record_key_use.
CREATE OR REPLACE FUNCTION auth.get_user_by_key(p_public_key TEXT)
RETURNS TEXT AS $$
    SELECT u.name
      FROM auth.user_keys k
      JOIN auth.users u ON u.user_id = k.user_id
     WHERE k.public_key = trim(p_public_key)
       AND k.revoked IS NULL
       AND (k.expires IS NULL OR k.expires > NOW());
$$ LANGUAGE sql;

--- Records a successful key authentication.  Also touches the user's
--- last_login so key-based and password-based access share one
--- 'when were they here last' answer.
CREATE OR REPLACE FUNCTION auth.record_key_use(p_public_key TEXT)
RETURNS BOOLEAN AS $$
DECLARE n_updated INTEGER;
BEGIN
    UPDATE auth.user_keys
       SET last_used = NOW()
     WHERE public_key = trim(p_public_key)
       AND revoked IS NULL;
    GET DIAGNOSTICS n_updated = ROW_COUNT;
    IF n_updated > 0 THEN
        UPDATE auth.users u
           SET last_login = NOW()
          FROM auth.user_keys k
         WHERE k.user_id = u.user_id
           AND k.public_key = trim(p_public_key);
    END IF;
    RETURN n_updated > 0;
END;
$$ LANGUAGE plpgsql;

--- Every key, with its state worked out once so that every listing
--- agrees on it:
---   active       TRUE if the key can log in right now -- not revoked
---                and not expired, the same test auth.get_user_by_key
---                applies.
---   invalidated  When it stopped working; NULL while active.  A key
---                that expired and was later revoked stopped at its
---                expiry, the earlier of the two.
---   reason       'revoked' or 'expired', whichever happened first;
---                NULL while active.
--- 'Right now' is NOW(), the transaction's start, so one transaction
--- calling several listings sees a single instant.
---
--- Granted to no role: it takes no name and no actor and returns
--- everybody's keys.  It runs from inside the definer functions.
CREATE OR REPLACE FUNCTION auth.key_states()
RETURNS TABLE(user_id BIGINT, key_name TEXT, algorithm TEXT,
              fingerprint TEXT, created TIMESTAMPTZ, expires TIMESTAMPTZ,
              revoked TIMESTAMPTZ, last_used TIMESTAMPTZ, active BOOLEAN,
              invalidated TIMESTAMPTZ, reason TEXT) AS $$
    SELECT k.user_id, k.key_name, k.algorithm,
           auth.key_fingerprint(k.public_key),
           k.created, k.expires, k.revoked, k.last_used,
           s.lapsed IS NULL AND k.revoked IS NULL,
           --- LEAST ignores NULLs.
           LEAST(s.lapsed, k.revoked),
           CASE WHEN s.lapsed IS NULL AND k.revoked IS NULL THEN NULL
                WHEN k.revoked IS NULL OR s.lapsed <= k.revoked THEN 'expired'
                ELSE 'revoked'
           END
      FROM auth.user_keys k
      --- The expiry, if it has passed.
      CROSS JOIN LATERAL
           (SELECT CASE WHEN k.expires <= NOW() THEN k.expires END
                   AS lapsed) s;
$$ LANGUAGE sql STABLE;

--- Lists a user's keys and their states.  The frontend's 'manage my
--- keys' page is built from this.  Never returns the key material a
--- client shouldn't need; public keys are public, so all columns are
--- safe here.  See auth.key_states for active, invalidated, and reason.
--- Dropped first because CREATE OR REPLACE cannot change the columns a
--- function returns.
DROP FUNCTION IF EXISTS auth.list_user_keys(TEXT);
CREATE OR REPLACE FUNCTION auth.list_user_keys(p_name TEXT)
RETURNS TABLE(key_name TEXT, algorithm TEXT, fingerprint TEXT,
              created TIMESTAMPTZ, expires TIMESTAMPTZ, revoked TIMESTAMPTZ,
              last_used TIMESTAMPTZ, active BOOLEAN,
              invalidated TIMESTAMPTZ, reason TEXT) AS $$
    SELECT k.key_name, k.algorithm, k.fingerprint, k.created, k.expires,
           k.revoked, k.last_used, k.active, k.invalidated, k.reason
      FROM auth.key_states() k
      JOIN auth.users u ON u.user_id = k.user_id
     WHERE u.name = lower(trim(p_name))
     ORDER BY k.created, k.key_name;
$$ LANGUAGE sql;

--------------------------------------------------------------------------
---                     Single-use login assertions                     ---
--------------------------------------------------------------------------
--- A key login presents a short-lived assertion the client signed.  A
--- valid signature proves the client holds the private key, but not
--- that it signed THIS request: anyone who captured an assertion could
--- present it again until it expires.  Each assertion carries a random
--- jti, and this table remembers every jti until its assertion expires,
--- so each one logs in once.
---
--- Scoped per key, so one client's jti cannot collide with another's.
--- Rows go once their assertion has expired: an expired assertion is
--- refused anyway, so forgetting its jti reopens nothing.
DROP TABLE IF EXISTS auth.consumed_assertions CASCADE;
CREATE TABLE auth.consumed_assertions(
    key_id BIGINT NOT NULL
        REFERENCES auth.user_keys(key_id) ON DELETE CASCADE,
    jti TEXT NOT NULL CHECK (length(jti) BETWEEN 1 AND 128),
    expires TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (key_id, jti)
);
CREATE INDEX consumed_assertions_expires_idx
    ON auth.consumed_assertions(expires);

--- Burns an assertion's jti.  Returns TRUE the first time a (key, jti)
--- is presented, FALSE on a replay, and FALSE if the key is not active
--- or the inputs are bad.  The backend calls this after verifying the
--- signature and claims, and mints a token only on TRUE.
---
--- The expiry is checked here against the database's clock as well as
--- in the backend.  That is what makes deleting old rows safe: a jti is
--- forgotten only after its assertion can no longer be consumed, whatever
--- the backend's clock says.
---
--- The upper bound keeps a client from parking rows for years with a
--- far-future exp.  The backend allows 60 seconds; five minutes leaves
--- room for clock skew between the two.
---
--- Two concurrent calls with the same jti cannot both win: the second
--- INSERT waits on the first's primary key and then does nothing.
CREATE OR REPLACE FUNCTION auth.consume_assertion(
    p_public_key TEXT, p_jti TEXT, p_expires TIMESTAMPTZ)
RETURNS BOOLEAN AS $$
DECLARE v_key_id BIGINT;
        n_inserted INTEGER;
BEGIN
    IF p_public_key IS NULL OR p_jti IS NULL OR p_expires IS NULL THEN
        RETURN FALSE;
    END IF;
    IF length(p_jti) = 0 OR length(p_jti) > 128 THEN
        RETURN FALSE;
    END IF;
    IF p_expires <= NOW() OR p_expires > NOW() + INTERVAL '5 minutes' THEN
        RETURN FALSE;
    END IF;
    SELECT key_id INTO v_key_id
      FROM auth.user_keys
     WHERE public_key = trim(p_public_key)
       AND revoked IS NULL
       AND (expires IS NULL OR expires > NOW());
    IF v_key_id IS NULL THEN
        RETURN FALSE;
    END IF;
    --- Housekeeping on the way through; the index keeps it cheap.
    DELETE FROM auth.consumed_assertions WHERE expires <= NOW();
    INSERT INTO auth.consumed_assertions (key_id, jti, expires)
        VALUES (v_key_id, p_jti, p_expires)
        ON CONFLICT DO NOTHING;
    GET DIAGNOSTICS n_inserted = ROW_COUNT;
    RETURN n_inserted > 0;
END;
